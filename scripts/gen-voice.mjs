import { mkdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MsEdgeTTS, OUTPUT_FORMAT } from 'msedge-tts';
import { VOICE_CLIP_TEXTS, slug } from '../packages/engine/src/voice.ts';

// Regenerates the bundled male-voice callout clips + the static manifest
// consumed by Mp3Speaker. Run via tsx (imports engine TS directly):
//
//   npx tsx scripts/gen-voice.mjs
//   VOICE=en-US-ChristopherNeural RATE=+12% npx tsx scripts/gen-voice.mjs
//   VOICE=en-US-AndrewNeural RATE=+18% PITCH=+2st VOLUME=+20% EMPHASIS=exclaim npx tsx scripts/gen-voice.mjs
//
// Knobs: VOICE (edge-tts voice), RATE / PITCH / VOLUME (SSML prosody),
// EMPHASIS: plain | exclaim (adds "!") | shout (CAPS + "!").
// Filenames always derive from the ORIGINAL text — emphasis only affects audio.
// Clip vocabulary is owned by the engine (src/voice.ts) — single source of truth.

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const VOICE_DIR = join(ROOT, 'app', 'assets', 'voice');
const TMP_DIR = join(ROOT, '.voice-tmp');
const MANIFEST_PATH = join(ROOT, 'app', 'audio', 'voice-manifest.ts');

const VOICE = process.env.VOICE ?? 'en-US-GuyNeural';
const RATE = process.env.RATE ?? '+8%';
const PITCH = process.env.PITCH ?? '+0Hz';
const VOLUME = process.env.VOLUME ?? '';
const EMPHASIS = process.env.EMPHASIS ?? 'plain';

function emphasize(text) {
  if (EMPHASIS === 'exclaim') return text.endsWith('!') ? text : `${text}!`;
  if (EMPHASIS === 'shout') return `${text.toUpperCase()}!`;
  return text;
}

rmSync(TMP_DIR, { recursive: true, force: true });
mkdirSync(TMP_DIR, { recursive: true });
mkdirSync(VOICE_DIR, { recursive: true });

const written = [];
for (const text of VOICE_CLIP_TEXTS) {
  const tts = new MsEdgeTTS();
  await tts.setMetadata(VOICE, OUTPUT_FORMAT.AUDIO_24KHZ_96KBITRATE_MONO_MP3);
  const prosody = { rate: RATE, pitch: PITCH };
  if (VOLUME) prosody.volume = VOLUME;
  const { audioFilePath } = await tts.toFile(TMP_DIR, emphasize(text), prosody);
  const target = join(VOICE_DIR, `${slug(text)}.mp3`);
  renameSync(audioFilePath, target);
  written.push(slug(text));
  console.log(`✓ ${slug(text)}.mp3`);
}
rmSync(TMP_DIR, { recursive: true, force: true });

const lines = written
  .map((name) => `  '${name}': require('../assets/voice/${name}.mp3'),`)
  .join('\n');
const manifest = `// GENERATED by scripts/gen-voice.mjs — do not edit by hand.
// Voice: ${VOICE}, rate: ${RATE}, pitch: ${PITCH}, volume: ${VOLUME || 'default'}, emphasis: ${EMPHASIS}
export const VOICE_CLIPS: Record<string, number> = {
${lines}
};
`;
writeFileSync(MANIFEST_PATH, manifest);
console.log(`\n${written.length} clips → app/assets/voice/ + manifest → app/audio/voice-manifest.ts`);
